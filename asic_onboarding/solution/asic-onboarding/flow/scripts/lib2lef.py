#!/usr/bin/env python3
"""flow/scripts/lib2lef.py -- placeholder LEF (abstract views) for a Liberty library.

    $(PYTHON) lib2lef.py <lib.lib> <out.lef> [--site-w 0.2] [--row-h 2.0]

Fusion Compiler synthesizes only with reference libraries that have a physical view of
every cell. A training or bring-up library that ships only a .lib/.db (no LEF, no NDM,
no technology file) can still be used for *logic* synthesis by giving each cell a
placeholder abstract: a CLASS CORE macro on one row of a dummy site, its width derived
from the Liberty 'area' (area / row height, exactly: FC reports frame area), one small M1 pin
per signal pin and VDD/VSS rails. flow/syn/fc_synth.tcl passes this LEF with the
bring-up technology file flow/syn/fc_bringup.tf to create_lib; FC then builds the NDM
cell library itself (library configuration, lm_shell) and the timing still comes from
the .db. The geometry is fiction: it makes the area of a placed design meaningless,
but the synthesis area (= sum of Liberty cell areas, see above) and timing are unaffected.
Not needed for a real PDK (SAED32, team PDK), which comes with LEF/NDM.
"""

import argparse
import math
import os
import sys

sys.path.insert(0, os.path.dirname(os.path.abspath(__file__)))
import liberty  # noqa: E402


def main():
    ap = argparse.ArgumentParser(description=__doc__.splitlines()[0])
    ap.add_argument('lib')
    ap.add_argument('out')
    ap.add_argument('--site-w', type=float, default=0.05, help='site width, um')
    ap.add_argument('--row-h', type=float, default=1.0, help='row (cell) height, um')
    ap.add_argument('--site', default='bringup_core', help='site name (must match the .tf Tile)')
    a = ap.parse_args()

    lib = liberty.parse(a.lib)
    sw, rh = a.site_w, a.row_h
    out = [
        '# generated by flow/scripts/lib2lef.py from ' + os.path.basename(a.lib),
        '# placeholder abstracts for logic synthesis only -- not a physical library',
        'VERSION 5.8 ;', 'BUSBITCHARS "[]" ;', 'DIVIDERCHAR "/" ;',
        'UNITS', '  DATABASE MICRONS 10000 ;', 'END UNITS', '',
        f'SITE {a.site}', '  CLASS CORE ;', '  SYMMETRY Y ;',
        f'  SIZE {sw:.3f} BY {rh:.3f} ;', f'END {a.site}', '',
    ]
    ncell = 0
    for cell in lib.sub('cell'):
        sig = [(n, d) for n, d, _ in liberty.pins(cell)]
        area = float(cell.attrs.get('area', '1') or 1)
        # Fusion Compiler reports the area of the *frame* (width x row height), so the width
        # must reproduce the Liberty area exactly: area / row height, on the site grid
        # (exact for class.lib, whose areas are integers; a 0-area cell gets one site).
        nsites = max(math.ceil(area / (sw * rh) - 1e-9), 1)
        w = nsites * sw
        pw = max(0.005, round(min(0.02, w / (4 * max(len(sig), 1))) / 0.005) * 0.005)  # never overlap
        out += [f'MACRO {cell.name}', '  CLASS CORE ;', '  ORIGIN 0 0 ;',
                f'  SIZE {w:.3f} BY {rh:.3f} ;', '  SYMMETRY X Y ;', f'  SITE {a.site} ;']
        for i, (n, d) in enumerate(sig):
            x0 = round((w * (i + 0.5) / len(sig) - pw / 2) / 0.005) * 0.005   # on the grid
            use = 'CLOCK' if cell.first('ff') is not None and \
                n in cell.first('ff').attrs.get('clocked_on', '') else 'SIGNAL'
            out += [f'  PIN {n}', f'    DIRECTION {d.upper()} ;', f'    USE {use} ;',
                    '    PORT', '      LAYER M1 ;',
                    f'        RECT {x0:.4f} {0.4 * rh:.3f} {x0 + pw:.4f} {0.6 * rh:.3f} ;',
                    '    END', f'  END {n}']
        for n, y0, y1, use in (('VDD', rh - 0.05, rh, 'POWER'), ('VSS', 0.0, 0.05, 'GROUND')):
            out += [f'  PIN {n}', '    DIRECTION INOUT ;', f'    USE {use} ;', '    SHAPE ABUTMENT ;',
                    '    PORT', '      LAYER M1 ;',
                    f'        RECT 0.000 {y0:.3f} {w:.3f} {y1:.3f} ;', '    END', f'  END {n}']
        out += [f'END {cell.name}', '']
        ncell += 1
    out.append('END LIBRARY')
    with open(a.out, 'w') as f:
        f.write('\n'.join(out) + '\n')
    print(f'lib2lef: {ncell} cells -> {a.out}')


if __name__ == '__main__':
    main()
